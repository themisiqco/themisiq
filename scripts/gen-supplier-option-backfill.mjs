#!/usr/bin/env node
// ── SUPPLIER RESPONSE VALUE BACKFILL: WRITE THE SQL ─────────────────────────────────────────────────
//
//   node scripts/gen-supplier-option-backfill.mjs > db/sql/supplier-option-values.sql
//
// Until 27 Sep 2026 lib/supply-chain/templates.ts stored an option's PROSE as the answer:
// supplier_responses.response held "Yes — board approved". Options now carry a stable `value`, and this
// emits the SQL that normalises existing rows onto it.
//
// ⚠️ GENERATED, NEVER TYPED. The map is 219 pairs; a hand-written copy would drift from the option list
// the first time a label was reworded, and a wrong pair silently rewrites a customer's answer into
// something no option matches. The generator reads templates.ts with the TypeScript parser, so the SQL is
// a function of the source and can be regenerated and diffed at any time.
//
// ⚠️ THE BACKFILL IS OPTIONAL, WHICH IS THE POINT. optionValue() accepts a value OR a legacy label, so the
// application reads both forms. Nothing breaks if this is never run, and nothing breaks while it is
// running — there is no window in which the code and the data disagree.
//
// ⚠️ FREE TEXT IS NOT TOUCHED. Only ids whose questions have options appear in the WHERE clause, so
// s3cat1_method, s3cat1_allocated and every textarea keep their contents.
//
// ⚠️ CHECKBOX ANSWERS ARE COMMA-JOINED, and only env_reporting is a checkbox. Its parts are mapped one at
// a time by the second statement, which is why that statement exists at all.

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import ts from 'typescript'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const REL = 'lib/supply-chain/templates.ts'
const src = readFileSync(join(ROOT, REL), 'utf8')
const sf = ts.createSourceFile(REL, src, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)

const questions = []
const visit = (n) => {
  if (ts.isObjectLiteralExpression(n)) {
    const get = (k) => n.properties.find(p => p.name && p.name.getText() === k)
    const id = get('id'), type = get('type'), opts = get('options')
    if (id && type && opts && ts.isArrayLiteralExpression(opts.initializer)) {
      const options = opts.initializer.elements.map(el => {
        const g = (k) => el.properties.find(p => p.name && p.name.getText() === k)
        return { value: g('value').initializer.text, label: g('label').initializer.text }
      })
      questions.push({ id: id.initializer.text, type: type.initializer.text, options })
    }
  }
  ts.forEachChild(n, visit)
}
visit(sf)

// Distinct by id: three ids appear in two templates with identical options.
const byId = new Map()
for (const q of questions) {
  if (!byId.has(q.id)) { byId.set(q.id, q); continue }
  const prev = byId.get(q.id)
  if (JSON.stringify(prev.options) !== JSON.stringify(q.options)) {
    console.error(`FATAL: ${q.id} appears twice with different options; the map would be ambiguous.`)
    process.exit(1)
  }
}
const qs = [...byId.values()]
const radios = qs.filter(q => q.type === 'radio')
const checkboxes = qs.filter(q => q.type === 'checkbox')
const q = (s) => `'${s.replace(/'/g, "''")}'`
const idList = qs.map(x => q(x.id)).join(', ')
const pairs = qs.flatMap(x => x.options.map(o => ({ id: x.id, label: o.label, value: o.value })))

const rows = (list) => list.map(p => `    (${q(p.id)}, ${q(p.label)}, ${q(p.value)})`).join(',\n')
const radioPairs = pairs.filter(p => radios.some(r => r.id === p.id))
const boxPairs = pairs.filter(p => checkboxes.some(c => c.id === p.id))

const out = []
out.push(`-- Supplier questionnaire: store option VALUES, not labels.`)
out.push(`-- Generated by scripts/gen-supplier-option-backfill.mjs from ${REL}. Do not edit by hand.`)
out.push(`-- ${pairs.length} pairs across ${qs.length} questions (${radios.length} radio, ${checkboxes.length} checkbox).`)
out.push(`--`)
out.push(`-- Run the PRE-FLIGHT first and keep its output: it is what tells you the backfill did what it said.`)
out.push(`-- The application reads labels and values alike, so this can run at any time, or never.`)
out.push('')
out.push(`-- ── PRE-FLIGHT ────────────────────────────────────────────────────────────────`)
out.push(`-- Answers still stored as label prose, per question. Zero after the backfill.`)
out.push(`--`)
out.push(`-- ⚠️ JOINED ON BOTH COLUMNS. Matching the response alone would count a label stored against a`)
out.push(`--    different question, and 'No' is an option of thirty of them.`)
out.push(`-- ⚠️ A CHECKBOX ROW HOLDING SEVERAL LABELS IS NOT COUNTED HERE, because its response equals no`)
out.push(`--    single label. Statement 2 of the backfill is what handles those; the verification query at`)
out.push(`--    the end is what confirms it did.`)
out.push(`select r.question_id, count(*) as rows_to_change`)
out.push(`  from supplier_responses r`)
out.push(`  join (values`)
out.push(rows(pairs))
out.push(`) as m(question_id, label, value)`)
out.push(`    on m.question_id = r.question_id and m.label = r.response`)
out.push(` group by r.question_id`)
out.push(` order by 2 desc, 1;`)
out.push('')
out.push(`-- ── BACKFILL ──────────────────────────────────────────────────────────────────`)
out.push(`begin;`)
out.push('')
out.push(`-- 1. Single-value answers (radio).`)
out.push(`update supplier_responses r`)
out.push(`   set response = m.value, updated_at = now()`)
out.push(`  from (values`)
out.push(rows(radioPairs))
out.push(`) as m(question_id, label, value)`)
out.push(` where r.question_id = m.question_id`)
out.push(`   and r.response = m.label;`)
out.push('')
out.push(`-- 2. Multi-value answers (checkbox), mapped part by part and rejoined in the stored order.`)
out.push(`--    A part that matches no label is kept as it is: an off-list answer stays visible as itself.`)
out.push(`with map(question_id, label, value) as (values`)
out.push(rows(boxPairs))
out.push(`), rewritten as (`)
out.push(`  select r.id,`)
out.push(`         string_agg(coalesce(m.value, p.part), ', ' order by p.ord) as response`)
out.push(`    from supplier_responses r`)
out.push(`    cross join lateral unnest(string_to_array(r.response, ',')) with ordinality as p(part, ord)`)
out.push(`    left join map m on m.question_id = r.question_id and m.label = btrim(p.part)`)
out.push(`   where r.question_id in (${checkboxes.map(c => q(c.id)).join(', ')})`)
out.push(`     and r.response is not null`)
out.push(`   group by r.id`)
out.push(`)`)
out.push(`update supplier_responses r`)
out.push(`   set response = w.response, updated_at = now()`)
out.push(`  from rewritten w`)
out.push(` where r.id = w.id and r.response <> w.response;`)
out.push('')
out.push(`commit;`)
out.push('')
out.push(`-- ── VERIFICATION ──────────────────────────────────────────────────────────────`)
out.push(`-- Must return no rows: every stored answer to an option question is now a value (or values).`)
out.push(`select question_id, response, count(*)`)
out.push(`  from supplier_responses`)
out.push(` where question_id in (${idList})`)
out.push(`   and response is not null`)
out.push(`   and response !~ '^[a-z0-9_]+(, ?[a-z0-9_]+)*$'`)
out.push(` group by 1, 2`)
out.push(` order by 3 desc;`)
out.push('')
out.push(`-- ── ROLLBACK ──────────────────────────────────────────────────────────────────`)
out.push(`-- The same two statements with label and value exchanged. Total, because every value came from`)
out.push(`-- exactly one label. Revert the code commit as well: the application reads both forms, so the`)
out.push(`-- order of the two does not matter.`)
out.push(`begin;`)
out.push('')
out.push(`update supplier_responses r`)
out.push(`   set response = m.label, updated_at = now()`)
out.push(`  from (values`)
out.push(rows(radioPairs))
out.push(`) as m(question_id, label, value)`)
out.push(` where r.question_id = m.question_id`)
out.push(`   and r.response = m.value;`)
out.push('')
out.push(`with map(question_id, label, value) as (values`)
out.push(rows(boxPairs))
out.push(`), rewritten as (`)
out.push(`  select r.id,`)
out.push(`         string_agg(coalesce(m.label, p.part), ', ' order by p.ord) as response`)
out.push(`    from supplier_responses r`)
out.push(`    cross join lateral unnest(string_to_array(r.response, ',')) with ordinality as p(part, ord)`)
out.push(`    left join map m on m.question_id = r.question_id and m.value = btrim(p.part)`)
out.push(`   where r.question_id in (${checkboxes.map(c => q(c.id)).join(', ')})`)
out.push(`     and r.response is not null`)
out.push(`   group by r.id`)
out.push(`)`)
out.push(`update supplier_responses r`)
out.push(`   set response = w.response, updated_at = now()`)
out.push(`  from rewritten w`)
out.push(` where r.id = w.id and r.response <> w.response;`)
out.push('')
out.push(`commit;`)
console.log(out.join('\n'))
